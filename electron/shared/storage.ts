/**
 * Storage types shared by main, preload and renderer (spec section 5).
 * Pure module: no Node / Electron imports.
 */

export type ItemKind = 'characters' | 'documents'
export const ITEM_KINDS: readonly ItemKind[] = ['characters', 'documents']

export type CharacterBackground = 'original' | 'transparent' | 'custom'

export type CharacterMeta = {
  id: string
  name: string
  createdAt: string
  background: CharacterBackground
}

export type DocumentMeta = {
  id: string
  name: string
  createdAt: string
  updatedAt: string
}

export type ItemMeta = CharacterMeta | DocumentMeta

/** Small list entry for the Dashboard name list. */
export type ItemSummary = { id: string; name: string }

/** Result of a Backup / Restore request, sent back to the renderer. */
export type BackupResult = { status: 'done'; file: string } | { status: 'cancelled' }

/** Item ids are generated by the app; only this safe shape is accepted (prevents path traversal). */
const ID_PATTERN = /^[a-z0-9-]{1,64}$/

export function isValidId(id: unknown): id is string {
  return typeof id === 'string' && ID_PATTERN.test(id)
}

export function isItemKind(kind: unknown): kind is ItemKind {
  return ITEM_KINDS.includes(kind as ItemKind)
}

/** Max length of a user-given item name. */
export const MAX_NAME_LENGTH = 100

/** Trims a name and caps its length; returns null when nothing is left. */
export function cleanName(name: unknown): string | null {
  if (typeof name !== 'string') return null
  const trimmed = name.trim().slice(0, MAX_NAME_LENGTH)
  return trimmed.length > 0 ? trimmed : null
}
